def run_file(vid):
    return os.path.join(AGENT_DIR, vid + ".run")


def current_run():
    """Для CLI: запуск агента, внутри которого идёт эта команда (или None)."""
    vid = os.environ.get("STUDIO_AGENT")
    if not vid:
        return None
    try:
        return open(run_file(vid), encoding="utf-8").read().strip() or None
    except OSError:
        return None


def journal(run, rec):
    """Обратная операция видео (set / add через CLI) — для отмены запуска."""
    os.makedirs(os.path.join(AGENT_DIR, "runs"), exist_ok=True)
    with open(os.path.join(AGENT_DIR, "runs", run + ".jsonl"), "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def _shot(A, vid, el, ts, name):
    """S12.4: кадр сцены редактора в момент ts -> <видео>/build/agent_runs/<name> (для карточки «Применено»: до / после)."""
    try:
        S, key = A.scapi(), "plan:" + vid
        tmp = os.path.join(S.work_dir(A, vid, el), "_agent_ab")
        os.makedirs(tmp, exist_ok=True)
        t = "%g" % round(float(ts), 2)
        for f in os.listdir(tmp):
            if f.startswith("element_") and f.endswith(".png"):
                os.remove(os.path.join(tmp, f))
        S.shoot(A, key, S.stage_url(A._docs(key)["port"], f"{vid}/{el}/work"), tmp, t)
        src = os.path.join(tmp, f"element_{t}.png")
        if not os.path.isfile(src):
            return None
        d = os.path.join(P.video(vid), "build", "agent_runs")
        os.makedirs(d, exist_ok=True)
        shutil.copy2(src, os.path.join(d, name))
        return "build/agent_runs/" + name
    except Exception as e:                              # кадр — приятное дополнение, запуск из-за него не падает
        print("! кадр до/после:", e)
        return None


def is_ch(vid):
    """S20.1: сессия канала (Библиотека, Стиль, Обложки, Рендеры, Память, YouTube) — id «ch-<канал>»."""
    return (vid or "").startswith("ch-")


def ch_of(vid):
    return P.channel(vid[3:]) if is_ch(vid) else None


def log_path(vid):
    if is_ch(vid):
        c = ch_of(vid)
        return os.path.join(c["dir"], "agent.jsonl") if c else os.path.join(AGENT_DIR, vid + ".jsonl")
    d = P.video(vid)
    return os.path.join(d, "agent.jsonl") if d else os.path.join(AGENT_DIR, vid + ".jsonl")


