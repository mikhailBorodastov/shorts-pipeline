def get_session(A, vid, model, mode):
    s = SESS.get(vid)
    try:
        mem = A.mmapi().prompt_text(vid[3:] if is_ch(vid) else P.index()["videos"].get(vid, {}).get("channel"), None if is_ch(vid) else vid)   # S12.10: правило — со следующего запуска
    except Exception:
        mem = ""
    bm = {} if is_ch(vid) else A.load("plan:" + vid).get("beatmap") or {}
    bm = f"{bm.get('status')}:{bm.get('v')}" if bm.get("status") == "ok" else ""   # S16: утвердили карту подачи — промпт сценария другой, сессия новая
    tok = getattr(s, "ctx_tok", 0) if s else 0
    heavy = bool(s and not s.busy and (tok > CTX_MAX or (tok > CTX_IDLE and time.time() - s.last > CACHE_SEC)))
    if not is_ch(vid):                                     # S22: правила ролика («🌐 на весь ролик») поменялись — новая сессия с ними
        try:
            mem += "\n" + video_rules(A.load("plan:" + vid))
        except Exception:
            pass
    if s and not heavy and s.alive() and s.model == model and s.mode == mode and getattr(s, "rules", 0) == RULES_REV and getattr(s, "mem", "") == mem and getattr(s, "bm", "") == bm:
        return s
    carry = _carry(s) if heavy else ""
    if s:
        if s.busy:
            raise RuntimeError("агент ещё работает — дождись или останови")
        s.close()
    s = SESS[vid] = Session(A, vid, model, mode)
    s.mem, s.bm = mem, bm
    s.carry = carry
    if heavy:
        s.add("note", f"история разговора выросла до {tok // 1000} тыс. токенов — начинаю новую сессию (экономия лимита), последние реплики передал")
    s.add("note", f"новая сессия · {model}" + (" · ✨ сборка" if mode == "build" else " · 📝 сценарий" if mode == "script" else " · 🎞 монтаж" if mode == "montage" else " · ⚡ быстрый монтаж" if mode == "fast" else ""))
    return s


_POST_LOCK = threading.Lock()


def post(vid, kind, text="", **kw):
    """Запись в чат видео без живой сессии — шаги задач (быстрый монтаж: план, писатели сцен). Сессия есть — в неё, нет — в agent.jsonl."""
    s = SESS.get(vid)
    if s:
        return s.add(kind, text, **kw)
    with _POST_LOCK:
        last = 0
        try:
            for ln in open(log_path(vid), encoding="utf-8"):
                try:
                    last = json.loads(ln).get("i", last)
                except ValueError:
                    pass
        except OSError:
            pass
        e = {"i": last + 1, "ts": now_ms(), "kind": kind, "text": text, "run": None, **kw}
        try:
            with open(log_path(vid), "a", encoding="utf-8") as f:
                f.write(json.dumps(e, ensure_ascii=False) + "\n")
        except OSError:
            pass
        return e


