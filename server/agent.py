def spawn(A, vid, model, mode):
    exe = A.claude_bin()
    if not exe:
        raise RuntimeError("не найден Claude Code (claude.exe)")
    os.makedirs(AGENT_DIR, exist_ok=True)
    sysf = os.path.join(AGENT_DIR, f"{vid}.{mode}.system.txt")
    A.write_text(sysf, system_prompt(A, vid, mode))
    # Bash — только команды студии и стенды; файлы — Read/Glob/Grep, правка — Write/Edit (где можно — в правилах промпта: версии lib fork, prefabs.js сцены, проект ролика)
    allowed = [f"Bash(python {STUDIO_PY}:*)", f"Bash(python {BLENDER_RUN}:*)", f"Bash(node {RENDER_PROP}:*)", f"Bash(node {RENDER_CHAR}:*)",
               "Read", "Grep", "Glob", "Write", "Edit"]
    tools = ["Bash", "Read", "Grep", "Glob", "Write", "Edit"]
    if mode in ("script", "build"):                      # S12.5: ресерч темы — поиск и чтение страниц
        tools += ["WebSearch", "WebFetch"]
        allowed += ["WebSearch", "WebFetch"]
    chd = (ch_of(vid) or {}).get("dir") if is_ch(vid) else None
    vdir = chd or P.video(vid) or P.ROOT
    cmd = [exe, "-p", "--safe-mode", "--no-session-persistence", "--input-format", "stream-json", "--output-format", "stream-json", "--verbose",
           "--tools", ",".join(tools), "--allowedTools", *allowed, "--permission-prompts", "none", "--system-prompt-file", sysf,
           "--add-dir", P.STUDIO, "--add-dir", chd or os.path.dirname(os.path.dirname(vdir)),       # движок и промпты; канал (библиотека)
           "--model", model]
    env = dict(os.environ, STUDIO_AGENT=vid, PYTHONIOENCODING="utf-8", PYTHONUTF8="1",
               BASH_DEFAULT_TIMEOUT_MS="600000", BASH_MAX_TIMEOUT_MS="600000")   # S22: job wait / --wait ждут до 9 мин одним ходом (было ~2 мин — лишние ходы)
    return subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=vdir, env=env,
                            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))


class Session:
    def __init__(self, A, vid, model, mode):
        self.A, self.vid, self.model, self.mode = A, vid, model, mode
        self.proc = spawn(A, vid, model, mode)
        self.rules = RULES_REV
        self.lock = threading.Lock()
        self.busy, self.run, self.last, self.ctx_scene, self.ending, self.acc = False, None, time.time(), None, None, None
        self.ctx_tok, self.carry = 0, ""                 # размер истории (токены последнего ответа); пересказ прошлой сессии для первой реплики
        self.entries = self._load()
        self.pending = {}                              # tool_use_id -> индекс записи шага
        threading.Thread(target=self._read, daemon=True).start()
        threading.Thread(target=self._err, daemon=True).start()

    def _load(self):
        out = []
        try:
            for ln in open(log_path(self.vid), encoding="utf-8"):
                try:
                    out.append(json.loads(ln))
                except ValueError:
                    pass
        except OSError:
            pass
        return out[-400:]

    def add(self, kind, text="", **kw):
        with self.lock:
            e = {"i": (self.entries[-1]["i"] + 1) if self.entries else 1, "ts": now_ms(), "kind": kind, "text": text, "run": self.run, **kw}
            self.entries.append(e)
            try:
                with open(log_path(self.vid), "a", encoding="utf-8") as f:
                    f.write(json.dumps(e, ensure_ascii=False) + "\n")
            except OSError:
                pass
            return e

    def patch(self, i, **kw):                            # результат шага дописывается к шагу (в файл — отдельной строкой «res»)
        with self.lock:
            for e in reversed(self.entries):
                if e["i"] == i:
                    e.update(kw); break
        self.add("res", kw.get("res", "")[:400], of=i, err=kw.get("err", False))

    def alive(self):
        return self.proc and self.proc.poll() is None

    def send(self, obj):
        self.proc.stdin.write((json.dumps(obj, ensure_ascii=False) + "\n").encode("utf-8"))
        self.proc.stdin.flush()

    def say(self, text, ctx=None, images=None):
        self.last = time.time()
        imgs = _images(images)
        head = ctx_text(self.A, self.vid, ctx)
        if not self.busy:
            self.run = "r" + uuid.uuid4().hex[:8]
            if self.mode in ("script", "build"):            # S12.5: версия сценария до запуска Claude
                try:
                    self.A.vdapi().script_snapshot(self.vid, "до запуска Claude")
                except Exception:
                    pass
            A = self.A
            os.makedirs(AGENT_DIR, exist_ok=True)
            A.write_text(run_file(self.vid), self.run)
            self.busy = True
            self.ctx_scene = (ctx or {}).get("el")
            if self.ctx_scene:
                A.scapi().LOCKS[A.scapi().skey("plan:" + self.vid, self.ctx_scene)] = "agent:" + self.vid
            ab = (ctx or {}).get("ab") or {}                 # S12.4: сцена и момент под курсором — кадр «до» сейчас, «после» — в конце запуска
            self.ab = None
            if ab.get("el") and ab.get("ts") is not None:
                self.ab = {"run": self.run, "el": ab["el"], "ts": float(ab["ts"]), "before": None}
                def before(ab=self.ab, vid=self.vid, A=A):
                    ab["before"] = _shot(A, vid, ab["el"], ab["ts"], ab["run"] + "-before.png")
                ab_t = threading.Thread(target=before, daemon=True)
                self.ab["thread"] = ab_t
                ab_t.start()
        self.route = (ctx or {}).get("route") or getattr(self, "route", "")   # S20.5: куда вести из уведомления «Claude спрашивает / готово»
        self.add("you", text, ctx=head, **({"images": [r for r, _ in imgs]} if imgs else {}))
        if imgs:                                          # картинки автора (вставлены в чат или приложены к пометкам): Claude смотрит их сам через Read
            text += ("\n\n[Картинки-референсы автора — посмотри КАЖДУЮ через Read, прежде чем править; в пометках они указаны как files/…: "
                     + "; ".join(f"{r} = {d}" for r, d in imgs) + "]")
        carry, self.carry = getattr(self, "carry", ""), ""
        self.send({"type": "user", "message": {"role": "user", "content": [{"type": "text", "text": (carry + "\n\n" if carry else "") + (head + "\n\n" if head else "") + text}]}})

    def stop(self):
        if self.busy and self.alive():
            self.send({"type": "control_request", "request_id": "int" + uuid.uuid4().hex[:6], "request": {"subtype": "interrupt"}})
            self.add("note", "■ остановлено автором")

    def close(self):
        try:
            if self.alive():
                self.proc.stdin.close()
                self.proc.wait(timeout=5)
        except Exception:
            pass
        try:
            if self.alive():
                P.kill_tree(self.proc)                         # S22: claude.exe со всеми детьми
        except Exception:
            pass
        self._unlock()

    def _unlock(self):
        if self.ctx_scene:
            L = self.A.scapi().LOCKS
            L.pop(self.A.scapi().skey("plan:" + self.vid, self.ctx_scene), None)
        self.ctx_scene = None

    def _finish(self, ok, text="", meta=None):
        run = self.run
        self.busy = False
        self.last = time.time()                               # пауза для кэша считается от конца ответа
        try:                                                  # монтаж агентом закончен — звук «готово» (если это не часть задачи монтажа: она прозвенит сама)
            ask = next((e.get("text") or "" for e in reversed(self.entries) if e.get("kind") == "you" and e.get("run") == run), "")
            if ok and self.mode in ("montage", "fast", "build") and ask.startswith(("🔊", "✋", "✍")):   # синхронизация, правки — не «Монтаж готов», а короткий «динь»
                self.A.chmapi().play("small")
            elif ok and self.mode in ("montage", "fast", "build") and not any(
                    j.key == "plan:" + self.vid and j.kind in ("fastmontage", "automontage") and j.status in ("running", "queued") for j in self.A.JOBS.values()):
                self.A.chmapi().play("montage")
            elif ok and self.mode == "script":                # сценарий дописан — «Сценарий готов»
                self.A.chmapi().play("script")
        except Exception:
            pass
        self._unlock()
        try:
            os.remove(run_file(self.vid))
        except OSError:
            pass
        ch = run_changes(self.A, self.vid, run) if run and not is_ch(self.vid) else {}
        if self.mode in ("script", "build"):                 # S12.5: версия сценария после запуска (если поменялся)
            try:
                self.A.vdapi().script_snapshot(self.vid, "Claude: " + ("сценарий" if self.mode == "script" else "сборка"))
            except Exception:
                pass
        self.add("done", text, ok=ok, undo=ch, **(meta or {}))
        self._notify_done(ok, run, text, meta)
        ab = getattr(self, "ab", None)
        if ab and ab.get("run") == run and (sum((ch.get("scenes") or {}).values()) or ch.get("plan")):
            def after(ab=ab, vid=self.vid, A=self.A, s=self):
                if ab.get("thread"):
                    ab["thread"].join(60)
                aft = _shot(A, vid, ab["el"], ab["ts"], ab["run"] + "-after.png")
                if ab.get("before") or aft:
                    s.add("shot", "", run=ab["run"], el=ab["el"], ts=ab["ts"], before=ab.get("before"), after=aft)
            threading.Thread(target=after, daemon=True).start()

    # ---- S20.5: лента 🔔 ----
    def _where(self):
        vid = None if is_ch(self.vid) else self.vid
        return vid, getattr(self, "route", "") or (f"#/v/{vid}" if vid else "#/lib"), (ch_of(self.vid) or {}).get("id") if is_ch(self.vid) else None

    def _notify_ask(self, text):
        import re
        m = re.search(r"\[\[(выбор|план|вопрос)[:\]]", text)
        if not m:
            return
        try:
            import notify_api
            vid, route, cid = self._where()
            q = [x for x in re.sub(r"\[\[[^\]]*\]\]", "", text).strip().splitlines() if x.strip()]
            title = {"план": "Claude ждёт «Делай» по плану", "выбор": "Claude спрашивает", "вопрос": "Claude спрашивает"}[m.group(1)]
            notify_api.add("ask", title, (q[-1] if q else "")[:300], vid, None, route, "❓", dedup=f"ask:{self.vid}:{self.run}:{m.group(1)}", channel=cid)
        except Exception as e:
            print("! notify ask:", e)

    def _notify_done(self, ok, run, text, meta):
        try:
            sec = (meta or {}).get("sec") or 0
            if sec < 25 and ok:                                  # короткий ответ — без уведомления (автор и так в чате)
                return
            last = next((e.get("text") or "" for e in reversed(self.entries) if e.get("kind") == "claude" and e.get("run") == run), "")
            if "[[" in last:                                     # ждёт ответа — уже есть «Claude спрашивает»
                return
            import notify_api
            vid, route, cid = self._where()
            notify_api.add("job" if ok else "error", "Claude в чате: готово" if ok else "Claude в чате: остановлено", (last or text or "").strip()[:300],
                           vid, None, route, "✨" if ok else "⚠", dedup=f"done:{self.vid}:{run}", channel=cid)
        except Exception as e:
            print("! notify done:", e)

    def _err(self):
        for ln in self.proc.stderr:
            s = ln.decode("utf-8", "replace").strip()
            if s:
                self.add("err", s[:400])

    def _read(self):
        for ln in self.proc.stdout:
            try:
                e = json.loads(ln)
            except ValueError:
                continue
            try:
                self._event(e)
            except Exception as ex:                      # a strange event must not kill the log
                self.add("err", f"лог: {ex}")
        if self.busy:
            self._finish(False, "сессия Claude закрылась")
        self.add("note", "сессия закрыта")

    def _event(self, e):
        ty = e.get("type")
        if ty == "assistant":
            u = (e.get("message") or {}).get("usage") or {}
            if u:
                self.ctx_tok = (u.get("input_tokens") or 0) + (u.get("cache_read_input_tokens") or 0) + (u.get("cache_creation_input_tokens") or 0)
            for c in (e.get("message") or {}).get("content") or []:
                if c.get("type") == "text" and c.get("text", "").strip():
                    self.add("claude", c["text"].strip())
                    self._notify_ask(c["text"].strip())
                elif c.get("type") == "tool_use":
                    x = self.add("step", step_text(c), tool=c.get("name"), cmd=tool_cmd(c))
                    self.pending[c.get("id")] = x["i"]
        elif ty == "user":
            for c in (e.get("message") or {}).get("content") or []:
                if isinstance(c, dict) and c.get("type") == "tool_result":
                    i = self.pending.pop(c.get("tool_use_id"), None)
                    body = c.get("content")
                    if isinstance(body, list):
                        body = " ".join(b.get("text", "") for b in body if isinstance(b, dict) and b.get("type") == "text")
                    if i:
                        self.patch(i, res=str(body or "")[:1500], err=bool(c.get("is_error")))
        elif ty == "system" and e.get("subtype") == "init":
            self.ending = None                            # следующий ход начался сразу (автор дописал, пока агент заканчивал) — тот же запуск
        elif ty == "result":
            ok = e.get("subtype") == "success"
            sec = round((e.get("duration_ms") or 0) / 1000)
            self.acc = {"cost": (self.acc or {}).get("cost", 0) + (e.get("total_cost_usd") or 0), "turns": (self.acc or {}).get("turns", 0) + (e.get("num_turns") or 0),
                        "sec": (self.acc or {}).get("sec", 0) + sec}
            for k, v in A_USAGE(e).items():                   # токены по видам — в «done» запуска (сводка: studio.py usage)
                self.acc[k] = self.acc.get(k, 0) + v
            text = "" if ok else ("прервано" if e.get("subtype") == "error_during_execution" else str(e.get("subtype")))
            token = self.ending = uuid.uuid4().hex
            def later():                                  # ждём 2.5 с: если автор дописал под конец, Claude сразу начнёт новый ход (init) — запуск продолжается
                time.sleep(2.5)
                if self.ending == token and self.busy:
                    acc, self.acc = self.acc, None
                    self._finish(ok, text, acc)
            threading.Thread(target=later, daemon=True).start()


